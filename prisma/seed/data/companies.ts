import type {
  CompanySizeRange,
  ContactSeniority,
  EmailStatus,
  EmailType,
  LegalForm,
  WebsiteKind,
  WhatsAppStatus,
} from "@/contracts/common";
import type { CompanySocials } from "@/contracts/enrichment";

export type FirstSource =
  | "google-places"
  | "jobs-serpapi"
  | "youtube-channels"
  | "apple-app-store"
  | "csv-import"
  | "manual";

export interface SeedContact {
  first?: string;
  last?: string;
  role?: string;
  seniority: ContactSeniority;
  /** A full address; role addresses use emailType ROLE. */
  email?: string;
  emailStatus?: EmailStatus;
  emailType?: EmailType;
  phone?: string;
  whatsapp?: WhatsAppStatus;
  linkedin?: string;
  /** Removed by a data-subject request: the row stays, with every personal field cleared. */
  anonymized?: boolean;
}

export interface SeedCompany {
  n: number;
  name: string;
  city: string;
  region?: string;
  country: "NG" | "GB" | "US" | "IE" | "CA";
  timezone: string;
  industry: string;
  legalForm: LegalForm;
  legalFormSource?: "companies-house" | "crawl-hint" | "cac-hint" | "places" | "manual";
  size: CompanySizeRange;
  /** Own website domain; null when the company has none. */
  domain: string | null;
  websiteKind: WebsiteKind;
  socials?: CompanySocials;
  phones: string[];
  source: FirstSource;
  /** Google place_id (a CompanySourceRef we may keep indefinitely). */
  placeId?: string;
  /** YouTube channel id (CompanySourceRef). */
  channelId?: string;
  copyrightYear?: number;
  platforms?: (
    "wordpress" | "wix" | "squarespace" | "shopify" | "webflow" | "godaddy" | "custom"
  )[];
  isActiveClient?: boolean;
  contacts: SeedContact[];
}

